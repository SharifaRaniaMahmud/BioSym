##HV calculation

import numpy as np

reference_point = np.array([1.1, 1.1], dtype=float)

def calculate_hv(front):
    # Convert to the two minimization objectives
    points = np.array(
        [(1.0 - r2, complexity) for r2, complexity in front],
        dtype=float
    )

    # Apply the SAME normalization to every front
    normalized = (points - objective_min) / (objective_max - objective_min)

    # Remove duplicate objective points
    normalized = np.unique(normalized, axis=0)

    # Sort by the first objective (ascending)
    normalized = normalized[np.argsort(normalized[:, 0])]

    # Calculate two-dimensional hypervolume
    hv = 0.0
    current_y = reference_point[1]

    for x, y in normalized:
        if x >= reference_point[0] or y >= reference_point[1]:
            continue

        if y < current_y:
            hv += (reference_point[0] - x) * (current_y - y)
            current_y = y

    return hv


