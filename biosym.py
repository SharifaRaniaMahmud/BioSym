    if len(front) == 0:
        return 0.0

    points = np.array([
        [1.0 - r2, complexity]
        for r2, complexity in front
    ], dtype=float)

    normalized = (points - obj_min) / (obj_max - obj_min)

    normalized = np.unique(normalized, axis=0)
    normalized = normalized[np.argsort(normalized[:, 0])]

    hv = 0.0
