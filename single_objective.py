def run_gp_evolution(
    X, y, feature_names,
    population_size=100,
    generations=100,
    max_depth=6,
    mutation_rate=.3
):
    # Initial population
    population = create_individual_population(
        n_individuals=population_size,
        max_depth=max_depth,
        feature_count=len(feature_names),
        X=X,
        y=y,
        feature_names=feature_names
    )

    gen_expr_log_path = '/content/drive/My Drive/GWL/r2_complexity/train219_val99_1obj_r2 of GP/train219_all_generation_expressions_log.txt'
    gen_expr_log = open(gen_expr_log_path, 'w')

    best_overall = None

    for gen in range(generations):

        parents = tournament_selection_r2(
            population,
            k=population_size,
            tournament_size=2
        )

        offspring = generate_offspring(
            parents=parents,
            num_offspring=population_size,
            max_depth=max_depth,
            feature_count=len(feature_names),
            mutation_rate=mutation_rate
        )

        combined_population = population + offspring

        population = sorted(
            combined_population,
            key=lambda ind: ind.r2,
            reverse=True
        )[:population_size]

        gen_best = max(population, key=lambda ind: ind.r2)

        if best_overall is None or gen_best.r2 > best_overall.r2:
            best_overall = gen_best

        gen_header = f"\nGeneration {gen + 1}"
        print(gen_header)
        gen_expr_log.write(gen_header + '\n')

        for i, ind in enumerate(population):
            expr_line = f"Individual {i + 1}, R²: {ind.r2:.4f}, Complexity: {ind.complexity:.4f}, Expr: {ind.readable}"
            print(expr_line)
            gen_expr_log.write(expr_line + '\n')

        generation_usage = Counter()
        for ind in population:
            generation_usage += count_features(ind.tree)
        feature_usage_log.append(generation_usage)

        for i, ind in enumerate(population):
            try:
                y_pred = [ind.tree.evaluate(row) for row in ind.X]
            except Exception:
                y_pred = [None] * len(ind.y)

            target_str = ",".join([f"{v:.4f}" for v in ind.y])
            pred_str = ",".join([f"{v:.4f}" if v is not None else "NaN" for v in y_pred])

            all_logs.append({
                "Generation": gen + 1,
                "Individual": i,
                "R2": ind.r2,
                "Complexity": ind.complexity,
                "Targets": target_str,
                "Predictions": pred_str,
            })

    gen_expr_log.close()
    return population, best_overall

