def split_args(s: str):
    args, depth, start = [], 0, 0
    for i, ch in enumerate(s):
        if ch == '(':
            depth += 1
        elif ch == ')':
            depth -= 1
        elif ch == ',' and depth == 0:
            args.append(s[start:i].strip())
            start = i + 1
    args.append(s[start:].strip())
    return args

def prefix_to_infix(expr: str) -> str:
    expr = expr.strip()

    # number
    if re.fullmatch(r"-?\d+(\.\d+)?", expr):
        return expr

    # variable name (underscore ok)
    if re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", expr):
        return expr

    # general call name(...)
    m = re.match(r"^([A-Za-z_+\-*/][A-Za-z0-9_]*)\((.*)\)$", expr)
    if not m:
        return expr

    name = m.group(1)
    inside = m.group(2).strip()
    args = split_args(inside)
    args_infix = [prefix_to_infix(a) for a in args]

    # binary ops
    if name in {"+", "-", "*", "/"} and len(args_infix) == 2:
        a, b = args_infix
        return f"({a} {name} {b})"

    # power
    if name == "pow" and len(args_infix) == 2:
        a, b = args_infix
        return f"({a} ^ {b})"

    # unary neg (if your GP uses neg(x))
    if name == "neg" and len(args_infix) == 1:
        return f"(-{args_infix[0]})"

    # other functions: cos(x), square(x), cube(x), exp(x), ...
    return f"{name}({', '.join(args_infix)})"

